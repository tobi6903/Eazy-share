// Constants and runtime settings. Nothing in here touches the network.
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const APP_NAME = 'eazy-share';
export const VERSION = '1.0.0';
export const DEFAULT_PORT = 8787;

/** Chrome native-messaging host name (must match extension/src/config.ts). */
export const NATIVE_HOST_NAME = 'com.eazyshare.host';

/**
 * The extension ships with a fixed public key in its manifest, so its ID never changes.
 * The native-messaging manifest only allows this one extension to talk to the host.
 */
export const EXTENSION_ID = 'nkadgfglmiljamnnnmjhbecncfkoihdh';

/** Repository root: compiled files live in <root>/dist/node/<folder>/, so go up three levels. */
export const PROJECT_ROOT = fileURLToPath(new URL('../../../', import.meta.url));

/** Everything generated by the build: compiled JS plus the ready-to-load web page and extension. */
export const DIST_DIR = path.join(PROJECT_ROOT, 'dist');

/** Compiled entry point, used to start the server as a background process. */
export const CLI_ENTRY = path.join(DIST_DIR, 'node', 'cli', 'main.js');

export interface Settings {
  host: string;
  port: number;
  /** Where state, logs and temporary transfers live. */
  home: string;
  /** How long an undismissed zip is kept. */
  transferTtlMs: number;
  /** How long an unfinished upload is kept. */
  stageTtlMs: number;
  /** A page refresh must not flash a device offline. */
  presenceGraceMs: number;
  /** Event-stream comment interval; keeps idle connections from being closed. */
  keepaliveMs: number;
  sweepIntervalMs: number;
}

export function defaultHome(): string {
  return process.env['EAZY_SHARE_HOME'] ?? path.join(os.homedir(), '.eazy-share');
}

export function createSettings(overrides: Partial<Settings> = {}): Settings {
  return {
    host: '0.0.0.0',
    port: DEFAULT_PORT,
    home: defaultHome(),
    transferTtlMs: 24 * 3600_000,
    stageTtlMs: 3600_000,
    presenceGraceMs: 3000,
    keepaliveMs: 25_000,
    sweepIntervalMs: 600_000,
    ...overrides,
  };
}

/** Locations derived from `settings.home`. */
export function layout(settings: Settings) {
  return {
    stagingDir: path.join(settings.home, 'staging'),
    zipsDir: path.join(settings.home, 'zips'),
    stateFile: path.join(settings.home, 'state.json'),
    logFile: path.join(settings.home, 'server.log'),
    binDir: path.join(settings.home, 'bin'),
  };
}
