// Registers the native-messaging host with Chromium-based browsers (one-time setup).
//
// What gets written depends on the OS:
//   macOS / Linux  a launcher script (<home>/bin/eazy-share-host) plus a JSON manifest in each
//                  installed browser's NativeMessagingHosts folder.
//   Windows        a launcher (<home>\bin\eazy-share-host.cmd) plus ONE JSON manifest
//                  (<home>\native\com.eazyshare.host.json); each browser finds it through a
//                  registry key under HKEY_CURRENT_USER (no administrator rights needed).
// The manifest names the one extension allowed to use the host.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { CLI_ENTRY, EXTENSION_ID, layout, NATIVE_HOST_NAME, type Settings } from '../core/config.js';

export const BROWSERS = ['chrome', 'chromium', 'brave', 'edge'] as const;
export type Browser = (typeof BROWSERS)[number];

export class InstallError extends Error {}

/** The Windows registry, as far as we need it. Injectable so tests don't touch the real one. */
export interface Registry {
  set(key: string, value: string): void;
  remove(key: string): void;
}

export const systemRegistry: Registry = {
  set: (key, value) => {
    execFileSync('reg', ['add', key, '/ve', '/t', 'REG_SZ', '/d', value, '/f'], { stdio: 'ignore', windowsHide: true });
  },
  remove: (key) => {
    execFileSync('reg', ['delete', key, '/f'], { stdio: 'ignore', windowsHide: true });
  },
};

export interface BrowserInfo {
  /** The browser's user-data folder; if it exists, the browser is installed. */
  userDataDir: string;
  /** Windows only: where the browser looks up native-messaging hosts. */
  registryKey?: string;
}

export function browserInfo(platform: NodeJS.Platform = process.platform, env: NodeJS.ProcessEnv = process.env): Record<Browser, BrowserInfo> {
  const home = os.homedir();
  if (platform === 'darwin') {
    const base = path.join(home, 'Library', 'Application Support');
    return {
      chrome: { userDataDir: path.join(base, 'Google', 'Chrome') },
      chromium: { userDataDir: path.join(base, 'Chromium') },
      brave: { userDataDir: path.join(base, 'BraveSoftware', 'Brave-Browser') },
      edge: { userDataDir: path.join(base, 'Microsoft Edge') },
    };
  }
  if (platform === 'linux') {
    const base = path.join(home, '.config');
    return {
      chrome: { userDataDir: path.join(base, 'google-chrome') },
      chromium: { userDataDir: path.join(base, 'chromium') },
      brave: { userDataDir: path.join(base, 'BraveSoftware', 'Brave-Browser') },
      edge: { userDataDir: path.join(base, 'microsoft-edge') },
    };
  }
  if (platform === 'win32') {
    const local = env['LOCALAPPDATA'] ?? path.join(home, 'AppData', 'Local');
    const key = (vendor: string): string => `HKCU\\Software\\${vendor}\\NativeMessagingHosts\\${NATIVE_HOST_NAME}`;
    return {
      chrome: { userDataDir: path.join(local, 'Google', 'Chrome', 'User Data'), registryKey: key('Google\\Chrome') },
      chromium: { userDataDir: path.join(local, 'Chromium', 'User Data'), registryKey: key('Chromium') },
      brave: { userDataDir: path.join(local, 'BraveSoftware', 'Brave-Browser', 'User Data'), registryKey: key('BraveSoftware\\Brave-Browser') },
      edge: { userDataDir: path.join(local, 'Microsoft', 'Edge', 'User Data'), registryKey: key('Microsoft\\Edge') },
    };
  }
  throw new InstallError(`Automatic setup supports Windows, macOS and Linux (this is ${platform}).`);
}

// --- launcher ----------------------------------------------------------------

export const launcherName = (platform: NodeJS.Platform = process.platform): string =>
  platform === 'win32' ? 'eazy-share-host.cmd' : 'eazy-share-host';

const shellQuote = (value: string): string => `'${value.replaceAll("'", `'\\''`)}'`;
const cmdQuote = (value: string): string => `"${value.replaceAll('%', '%%')}"`;

/** The small script the browser runs; it starts this project's native host with the right Node. */
export function writeLauncher(settings: Settings, platform: NodeJS.Platform = process.platform): string {
  const { binDir } = layout(settings);
  fs.mkdirSync(binDir, { recursive: true });
  const launcher = path.join(binDir, launcherName(platform));

  if (platform === 'win32') {
    const lines = [
      '@echo off',
      'rem Generated by `eazy-share install-host`. Re-run that command instead of editing this file.',
      `${cmdQuote(process.execPath)} ${cmdQuote(CLI_ENTRY)} --home ${cmdQuote(settings.home)} native-host`,
    ];
    fs.writeFileSync(launcher, `${lines.join('\r\n')}\r\n`);
  } else {
    fs.writeFileSync(
      launcher,
      '#!/bin/sh\n' +
        '# Generated by `eazy-share install-host`. Re-run that command instead of editing this file.\n' +
        `exec ${shellQuote(process.execPath)} ${shellQuote(CLI_ENTRY)} --home ${shellQuote(settings.home)} native-host\n`,
      { mode: 0o755 },
    );
    fs.chmodSync(launcher, 0o755);
  }
  return launcher;
}

// --- manifest ----------------------------------------------------------------

export interface HostManifest {
  name: string;
  description: string;
  path: string;
  type: 'stdio';
  allowed_origins: string[];
}

export function manifestFor(launcher: string, extensionId: string = EXTENSION_ID): HostManifest {
  return {
    name: NATIVE_HOST_NAME,
    description: 'Eazy-share: starts and stops the local file-sharing server',
    path: launcher,
    type: 'stdio',
    allowed_origins: [`chrome-extension://${extensionId}/`],
  };
}

function writeManifest(folder: string, manifest: string): string {
  fs.mkdirSync(folder, { recursive: true });
  const file = path.join(folder, `${NATIVE_HOST_NAME}.json`);
  fs.writeFileSync(file, manifest);
  return file;
}

// --- install / uninstall ---------------------------------------------------------

export interface InstallOptions {
  /** Limit to these browsers (default: every installed one). */
  browsers?: Browser[];
  /** Write only the manifest, into this folder (testing, or an unsupported browser). */
  dest?: string;
  extensionId?: string;
  /** For tests. */
  platform?: NodeJS.Platform;
  env?: NodeJS.ProcessEnv;
  registry?: Registry;
}

export interface InstallResult {
  /** Manifest files written. */
  files: string[];
  /** Windows registry keys set. */
  registryKeys: string[];
}

export function install(settings: Settings, options: InstallOptions = {}): InstallResult {
  const platform = options.platform ?? process.platform;
  const launcher = writeLauncher(settings, platform);
  const manifest = `${JSON.stringify(manifestFor(launcher, options.extensionId), null, 2)}\n`;

  if (options.dest) return { files: [writeManifest(options.dest, manifest)], registryKeys: [] };

  const known = browserInfo(platform, options.env);
  const wanted = options.browsers?.length ? options.browsers : [...BROWSERS];
  const unknown = wanted.filter((b) => !(b in known));
  if (unknown.length) throw new InstallError(`Unknown browser(s): ${unknown.join(', ')}. Choose from: ${BROWSERS.join(', ')}.`);
  // Only touch browsers that are actually installed (their user-data folder exists).
  const present = wanted.filter((b) => fs.existsSync(known[b].userDataDir));
  if (present.length === 0) throw new InstallError('No supported browser found. Use --dest to choose a folder manually.');

  if (platform === 'win32') {
    // Windows finds the manifest through the registry, so one file serves every browser.
    const file = writeManifest(path.join(settings.home, 'native'), manifest);
    const registry = options.registry ?? systemRegistry;
    const registryKeys = present.map((b) => known[b].registryKey as string);
    for (const key of registryKeys) registry.set(key, file);
    return { files: [file], registryKeys };
  }
  const files = present.map((b) => writeManifest(path.join(known[b].userDataDir, 'NativeMessagingHosts'), manifest));
  return { files, registryKeys: [] };
}

/** Remove what `install` wrote. Returns what was actually removed. */
export function uninstall(settings: Settings, options: Pick<InstallOptions, 'dest' | 'platform' | 'env' | 'registry'> = {}): InstallResult {
  const platform = options.platform ?? process.platform;
  const files: string[] = [];
  const registryKeys: string[] = [];
  const removeFile = (file: string): void => {
    if (fs.existsSync(file)) {
      fs.rmSync(file);
      files.push(file);
    }
  };

  if (options.dest) {
    removeFile(path.join(options.dest, `${NATIVE_HOST_NAME}.json`));
  } else if (platform === 'win32') {
    const registry = options.registry ?? systemRegistry;
    for (const info of Object.values(browserInfo(platform, options.env))) {
      try {
        registry.remove(info.registryKey as string);
        registryKeys.push(info.registryKey as string);
      } catch {
        /* key wasn't there */
      }
    }
    removeFile(path.join(settings.home, 'native', `${NATIVE_HOST_NAME}.json`));
  } else {
    for (const info of Object.values(browserInfo(platform, options.env))) {
      removeFile(path.join(info.userDataDir, 'NativeMessagingHosts', `${NATIVE_HOST_NAME}.json`));
    }
  }
  fs.rmSync(path.join(layout(settings).binDir, launcherName(platform)), { force: true });
  return { files, registryKeys };
}
